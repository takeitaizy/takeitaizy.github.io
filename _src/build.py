#!/usr/bin/env python3
"""Build the site's HTML pages from _src/. Standard library only.

    python3 _src/build.py           write the pages
    python3 _src/build.py --check   fail if a page on disk differs from its source (CI runs this)

Every page shares _src/layout.html (head, nav, side menu, footer, tab bar,
WhatsApp button, storage notice). A page source in _src/pages/ starts with a
comment of `key: value` lines, then named blocks:

    <!--page
    out: work.html          file written at the repo root (GitHub Pages serves it at /work)
    path: /work             canonical path
    nav: work               the menu item marked aria-current="page" (one of NAV below)
    form: work              utm_content the contact form reports for this page
    title: ...              Hebrew <title>; title_en is the English one
    description: ...        Hebrew meta description; description_en is the English one
    -->
    <!-- @block head -->...<!-- @end -->   extra head content (structured data)
    <!-- @block main -->...<!-- @end -->   the page body inside <main>

Optional keys (defaults below): og_description, wa_text, wa_text_en, contact_h,
contact_h_en, contact_lead, contact_lead_en, contact_cta, contact_cta_en, and the
block contact_steps. `key: value` values are plain text and get HTML-escaped;
blocks are HTML. Inside blocks and partials, {{name}} inserts a value and
{{> name}} inserts _src/partials/name.html. An unknown name stops the build.

The site is still static files on GitHub Pages; site.css and site.js at the root
are shared by every page and are edited directly.
"""
import html
import re
import sys
from pathlib import Path
from urllib.parse import quote

SRC = Path(__file__).resolve().parent
ROOT = SRC.parent
WA_NUMBER = "972503255115"
NOTICE = "<!-- Generated by _src/build.py from _src/pages/{name}. Edit the source, then run: python3 _src/build.py -->"

DEFAULTS = {
    "wa_text": "היי אושר, הגעתי מהאתר של Take It AIzy",
    "wa_text_en": "Hi Osher, I found you through the Take It AIzy website",
    "contact_h": "ספרו לנו מה גוזל לכם הכי הרבה זמן",
    "contact_h_en": "Tell us what eats most of your time",
    "contact_lead": "חוזרים אליכם תוך יום עסקים עם מחשבות ראשונות. שיחת האפיון הראשונה ללא עלות.",
    "contact_lead_en": "We get back to you within one business day with first thoughts. The first needs call is free of charge.",
    "contact_cta": "לשיחת אפיון ללא עלות",
    "contact_cta_en": "Book a free needs call",
}
DEFAULT_STEPS = """        <li><span><b data-en="Fill in a short form">ממלאים טופס קצר</b><span data-en="What your business does, what takes too long, and what you wish happened on its own.">מה העסק עושה, מה לוקח יותר מדי זמן, ומה הייתם רוצים שיקרה מעצמו.</span></span></li>
        <li><span><b data-en="One of us gets back to you">אחד מאיתנו חוזר אליכם</b><span data-en="Within one business day, with first questions and thoughts.">תוך יום עסקים, עם שאלות ראשונות ומחשבות.</span></span></li>
        <li><span><b data-en="A short intro call">שיחת היכרות קצרה</b><span data-en="You leave with a clear direction: what is worth building first, and whether you need it at all.">יוצאים ממנה עם כיוון ברור: מה שווה לבנות קודם, ואם בכלל צריך.</span></span></li>"""
REQUIRED = ("out", "path", "nav", "form", "title", "title_en", "description", "description_en")
NAV = ("home", "work", "workshops", "whatsapp-agent", "management-system", "ai-agents")
TOKEN = re.compile(r"\{\{\s*(>?)\s*([\w-]+)\s*\}\}")


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"\s*<!--page\n(.*?)\n-->\n", text, re.S)
    if not m:
        sys.exit(f"{path.name}: missing the <!--page ... --> header")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            sys.exit(f"{path.name}: bad header line {line!r}")
        meta[key.strip()] = value.strip()
    blocks = dict(re.findall(r"<!-- @block ([\w-]+) -->\n(.*?)<!-- @end -->", text[m.end():], re.S))
    return meta, blocks


def render(text, values, where):
    def sub(match):
        partial, name = match.groups()
        if partial:
            file = SRC / "partials" / f"{name}.html"
            if not file.exists():
                sys.exit(f"{where}: no partial {name}")
            return render(file.read_text(encoding="utf-8"), values, f"partial {name}")
        if name not in values:
            sys.exit(f"{where}: unknown name {{{{{name}}}}}")
        return values[name]
    return TOKEN.sub(sub, text)


def build_page(path, layout):
    meta, blocks = parse(path)
    missing = [k for k in REQUIRED if k not in meta]
    if missing:
        sys.exit(f"{path.name}: missing {', '.join(missing)}")
    if meta["nav"] not in NAV:
        sys.exit(f"{path.name}: nav must be one of {NAV}")
    plain = {**DEFAULTS, **meta}
    plain.setdefault("og_description", plain["description"])
    values = {k: html.escape(v, quote=True) for k, v in plain.items()}
    values["wa_href"] = f"https://wa.me/{WA_NUMBER}?text={quote(plain['wa_text'], safe='')}"
    values["wa_href_en"] = f"https://wa.me/{WA_NUMBER}?text={quote(plain['wa_text_en'], safe='')}"
    for item in NAV:
        values[f"cur_{item}"] = ' aria-current="page"' if meta["nav"] == item else ""
    values["contact_steps"] = render(blocks.get("contact_steps", DEFAULT_STEPS).rstrip("\n"), values, path.name)
    values["head"] = render(blocks.get("head", "").rstrip("\n"), values, path.name)
    if "main" not in blocks:
        sys.exit(f"{path.name}: missing the main block")
    values["main"] = render(blocks["main"].rstrip("\n"), values, path.name)
    page = render(layout, values, "layout")
    first, rest = page.split("\n", 1)
    return meta["out"], f"{first}\n{NOTICE.format(name=path.name)}\n{rest}"


def main():
    check = "--check" in sys.argv[1:]
    layout = (SRC / "layout.html").read_text(encoding="utf-8")
    stale = []
    for path in sorted((SRC / "pages").glob("*.html")):
        out, page = build_page(path, layout)
        target = ROOT / out
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != page:
                stale.append(out)
        else:
            target.write_text(page, encoding="utf-8")
            print(f"wrote {out}")
    if stale:
        sys.exit("out of date, run python3 _src/build.py and commit: " + ", ".join(stale))
    if check:
        print("pages match their sources")


if __name__ == "__main__":
    main()
